def test_sync_sdk_major_divergence(tmp: Path) -> None:
    """SDK-only major bump: satellites stay --locked-viable, App version untouched."""
    root = make_fixture(tmp)
    rv = load_module(root, "release_version")
    changed = rv.sync_sdk("3.0.0")
    assert any(entry == "Cargo.toml" for entry in changed)
    # SDK files moved; the [package] header (version.workspace) is untouched.
    cargo = (root / "Cargo.toml").read_text(encoding="utf-8")
    assert "version.workspace = true" in cargo
    assert 'version = "3.0.0"' in cargo
    assert lock_block_version(root, "Cargo.lock", "mcpstore") == "3.0.0"
    assert lock_block_version(root, "Cargo.lock", "mcpstore_python") == "3.0.0"
    assert lock_block_version(root, "Cargo.lock", "serde") == "1.0.210"
    assert lock_block_version(root, "satellite/python/uv.lock", "mcpstore") == "3.0.0"
    assert lock_block_version(root, "satellite/python/uv.lock", "some-dev-tool") == "0.1.0"
    assert 'version = "3.0.0"' in (root / "satellite/python/pyproject.toml").read_text(encoding="utf-8")
    assert '__version__ = "3.0.0"' in (root / "satellite/python/mcpstore/__init__.py").read_text(encoding="utf-8")
    # Cross-domain contract maintained by the same sync: req tracks the new
    # minor and the satellite SDK lock mirrors are re-locked.
    cli_cargo = (root / "satellite/cli/Cargo.toml").read_text(encoding="utf-8")
    assert 'version = "3.0"' in cli_cargo
    assert 'version = "3.0.0"' not in cli_cargo
    assert lock_block_version(root, "satellite/cli/Cargo.lock", "mcpstore") == "3.0.0"
    assert lock_block_version(root, "satellite/desktop/tauri/Cargo.lock", "mcpstore") == "3.0.0"
    # App's own version is untouched everywhere.
    assert f'version = "{BASE_APP}"' in cli_cargo
    for rel, marker in app_version_files(root):
        assert marker in (root / rel).read_text(encoding="utf-8"), rel
    assert lock_block_version(root, "satellite/cli/Cargo.lock", "mcpstore-cli") == BASE_APP
    assert lock_block_version(root, "satellite/desktop/tauri/Cargo.lock", "mcpstore-cli") == BASE_APP
    assert lock_block_version(root, "satellite/desktop/tauri/Cargo.lock", "mcpstore-tauri") == BASE_APP
    # SDK=3.0.0 with App=2.3.1: every domain verifies green, no second sync needed.
    assert rv.verify_sdk() == "3.0.0"
    assert rv.verify_app() == BASE_APP
    assert rv.verify_release_metadata("all") == {"sdk": "3.0.0", "app": BASE_APP}


def test_sync_app_only_touches_app_domain(tmp: Path) -> None:
    root = make_fixture(tmp)
    rv = load_module(root, "release_version")
    changed = rv.sync_app("4.5.6")
