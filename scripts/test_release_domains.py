def test_tag_rules_per_domain(tmp: Path) -> None:
    root = make_fixture(tmp)
    pf = load_module(root, "release_preflight")

    # SDK: exact sdk-v<version> only, never prerelease, never plain v.
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="sdk-v3.0.0"):
        pf.verify_release_tag("sdk", "3.0.0", allow_prerelease=False)
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="sdk-v3.0.0-rc.1"):
        expect_exit(lambda: pf.verify_release_tag("sdk", "3.0.0", allow_prerelease=True), "sdk-v3.0.0")
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v3.0.0"):
        expect_exit(lambda: pf.verify_release_tag("sdk", "3.0.0", allow_prerelease=False), "sdk-v3.0.0")
    with github_env(GITHUB_REF_TYPE="branch", GITHUB_REF_NAME="main"):
        expect_exit(lambda: pf.verify_release_tag("sdk", "3.0.0", allow_prerelease=False), "tag")

    # App: exact v<version>, or v<version>-<prerelease> only with the opt-in flag.
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v4.5.6"):
        pf.verify_release_tag("app", "4.5.6", allow_prerelease=False)
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v4.5.6-rc.1"):
        pf.verify_release_tag("app", "4.5.6", allow_prerelease=True)
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v4.5.6-rc.1"):
        expect_exit(lambda: pf.verify_release_tag("app", "4.5.6", allow_prerelease=False), "v4.5.6")
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="sdk-v4.5.6"):
        expect_exit(lambda: pf.verify_release_tag("app", "4.5.6", allow_prerelease=False), "v4.5.6")


