def _run_preflight(pf, *args: str) -> None:
    with argv(*args):
        pf.main()


def test_assets_naming_follows_exact_tag(tmp: Path) -> None:
    root = make_fixture(tmp)
    assets = load_module(root, "prepare_github_release_assets")
    dist = root / "dist" / "darwin-arm64"
    dist.mkdir(parents=True)
    (dist / "mcpstore").write_bytes(b"fake-binary")
    (dist / "SHA256SUMS").write_text("0" * 64 + "  mcpstore\n", encoding="utf-8")

    def run_assets() -> None:
        with argv("--dist-root", "dist", "--assets-dir", "release-assets"):
            assets.main()

    # Local run (no tag env): stable tag from the App canonical.
    with github_env(GITHUB_REF_TYPE=None, GITHUB_REF_NAME=None):
        run_assets()
    assert (root / "release-assets" / f"mcpstore-v{BASE_APP}-darwin-arm64.tar.gz").exists()

    # Candidate tag: archive name carries the exact tag suffix so the download
    # URL install.sh derives from the tag resolves.
    shutil.rmtree(root / "release-assets")
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME=f"v{BASE_APP}-rc.1"):
        run_assets()
    archive = root / "release-assets" / f"mcpstore-v{BASE_APP}-rc.1-darwin-arm64.tar.gz"
    assert archive.exists()
    sums = (root / "release-assets" / "SHA256SUMS.txt").read_text(encoding="utf-8")
    assert archive.name in sums
    with archive.open("rb") as file, tarfile.open(fileobj=file) as tar:
        assert "mcpstore" in tar.getnames()

    # A tag that does not match the App canonical is rejected loudly.
    shutil.rmtree(root / "release-assets")
    with github_env(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v9.9.9"):
        expect_exit(run_assets, "does not match App version")


def test_real_repo_smoke() -> None:
    """Real-repository smoke, derived from live manifests (no pinned version:
    stays green after any actual sync). Same-version syncs are no-ops."""
    spec = importlib.util.spec_from_file_location("release_version_real", SCRIPTS_DIR / "release_version.py")
    rv = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rv)
    sdk = rv.read_sdk_version()
    app = rv.read_app_version()
    assert re.fullmatch(r"\d+\.\d+\.\d+", sdk), sdk
    assert re.fullmatch(r"\d+\.\d+\.\d+", app), app

    checks: list[tuple[list[str], dict[str, str], int]] = [
        (["scripts/release_preflight.py"], {}, 0),
        (["scripts/release_preflight.py", "--domain", "sdk"], {}, 0),
        (["scripts/release_preflight.py", "--domain", "app"], {}, 0),
        (
            ["scripts/release_preflight.py", "--domain", "sdk", "--require-tag"],
            {"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": f"sdk-v{sdk}"},
            0,
        ),
        (
            ["scripts/release_preflight.py", "--domain", "sdk", "--require-tag"],
            {"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": f"v{sdk}"},
            1,
        ),
        (
            ["scripts/release_preflight.py", "--domain", "app", "--require-tag", "--allow-prerelease-tag"],
            {"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": f"v{app}-rc.9"},
            0,
        ),
        (
            ["scripts/release_preflight.py", "--domain", "app", "--require-tag"],
            {"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": f"v{app}-rc.9"},
            1,
        ),
        (["scripts/sync_version.py", "sdk", sdk], {}, 0),
        (["scripts/sync_version.py", "app", app], {}, 0),
        (["-c", "from scripts.prepare_github_release_assets import sha256; print(sha256.__name__)"], {}, 0),
        (["bash", "-n", "scripts/build_target.sh"], {}, 0),
        (["bash", "-n", "scripts/smoke_test.sh"], {}, 0),
        (["bash", "-n", "install.sh"], {}, 0),
    ]
    for args, env_extra, expected in checks:
        if args[:1] == ["bash"]:
            proc = subprocess.run(args, cwd=REPO_ROOT, capture_output=True, text=True, timeout=60)
        else:
            proc = run_script(REPO_ROOT, *args, env_extra=env_extra)
