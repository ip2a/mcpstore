def load_module(root: Path, name: str):
    """Load a script from the fixture with a fresh fixture release_version.

    The fixture scripts import `release_version` by module name; register the
    fixture's copy under that name for the duration of the load so the import
    binds to this fixture (never to a previous test's, and never polluting the
    global namespace afterwards).
    """
    scripts = root / "scripts"
    rv_spec = importlib.util.spec_from_file_location("release_version_fixture", scripts / "release_version.py")
    rv_module = importlib.util.module_from_spec(rv_spec)
    rv_spec.loader.exec_module(rv_module)

    previous = sys.modules.get("release_version")
    sys.modules["release_version"] = rv_module
    try:
        spec = importlib.util.spec_from_file_location(f"{name}_fixture", scripts / f"{name}.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        if previous is not None:
            sys.modules["release_version"] = previous
        else:
            sys.modules.pop("release_version", None)
    return module


def lock_block_version(root: Path, rel: str, name: str) -> str:
    text = (root / rel).read_text(encoding="utf-8")
    match = re.search(rf'\[\[package\]\]\nname = "{re.escape(name)}"\nversion = "([^"]+)"', text)
    assert match, f"no [[package]] block for {name} in {rel}"
    return match.group(1)


@contextlib.contextmanager
def github_env(**values):
    old = {key: os.environ.get(key) for key in values}
    for key, value in values.items():
        if value is None:
            os.environ.pop(key, None)
        else:
            os.environ[key] = value
    try:
        yield
    finally:
        for key, value in old.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


@contextlib.contextmanager
def argv(*args):
    old = sys.argv
    sys.argv = ["test", *args]
    try:
        yield
    finally:
        sys.argv = old


def expect_exit(fn, *contains) -> str:
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            fn()
    except SystemExit as exit_info:
        code = str(exit_info.code)
        assert exit_info.code not in (None, 0), f"expected failing exit, got {exit_info.code!r}"
        for fragment in contains:
            assert fragment in code, f"{fragment!r} not in {code!r}"
        return code
    raise AssertionError(f"expected SystemExit from {fn}, none raised")


def run_script(repo: Path, *args: str, env_extra: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    env = {**os.environ}
    for key in ("GITHUB_REF_TYPE", "GITHUB_REF_NAME"):
        env.pop(key, None)
    env.update(env_extra or {})
    return subprocess.run(
        [sys.executable, *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )


def app_version_files(root: Path, version: str = BASE_APP) -> list[str]:
    """Assert every App-version carrier holds `version`; return Cargo text checks."""
    conf = json.loads((root / "satellite/desktop/tauri/tauri.conf.json").read_text(encoding="utf-8"))
    web = json.loads((root / "satellite/web/package.json").read_text(encoding="utf-8"))
    main_pkg = json.loads((root / "satellite/npm/packages/mcpstore/package.json").read_text(encoding="utf-8"))
    bin_pkg = json.loads((root / "satellite/npm/packages/mcpstore-bin-test-x64/package.json").read_text(encoding="utf-8"))
    web_lock = json.loads((root / "satellite/web/package-lock.json").read_text(encoding="utf-8"))
    assert conf["version"] == web["version"] == main_pkg["version"] == bin_pkg["version"] == version
    assert web_lock["version"] == web_lock["packages"][""]["version"] == version
    assert web_lock["packages"]["some-dep"]["version"] == "1.0.0"
    assert all(v == version for v in main_pkg["optionalDependencies"].values())
    return [
        ("satellite/cli/Cargo.toml", f'version = "{version}"'),
        ("satellite/desktop/tauri/Cargo.toml", f'version = "{version}"'),
    ]


