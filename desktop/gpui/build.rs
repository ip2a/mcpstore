use std::env;
use std::fs;
use std::io;
use std::path::PathBuf;

fn main() -> io::Result<()> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let i18n_dir = manifest_dir.join("../../i18n");
    let out_file = PathBuf::from(env::var("OUT_DIR").unwrap()).join("i18n_generated.rs");
    println!("cargo:rerun-if-changed={}", i18n_dir.display());

    let mut locales = Vec::new();
    for entry in fs::read_dir(&i18n_dir)? {
        let path = entry?.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("yaml") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let locale = path.file_stem().unwrap().to_string_lossy().to_string();
        let pairs = parse_flat(&fs::read_to_string(&path)?);
        locales.push((locale, pairs));
    }
    locales.sort_by(|a, b| a.0.cmp(&b.0));
    if locales.is_empty() {
        return Err(io::Error::new(io::ErrorKind::NotFound, "no i18n yaml"));
    }

    let mut keys: Vec<String> = locales[0].1.iter().map(|(k, _)| k.clone()).collect();
    keys.sort();
    for (_, pairs) in &locales {
        let mut theirs: Vec<&str> = pairs.iter().map(|(k, _)| k.as_str()).collect();
        theirs.sort_unstable();
        let mine: Vec<&str> = keys.iter().map(String::as_str).collect();
        if theirs != mine {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "i18n yaml key sets differ",
            ));
        }
    }

    let mut out = String::from("// Generated by build.rs from i18n/*.yaml. Do not edit.\n\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Locale {\n");
    for (locale, _) in &locales {
        out.push_str(&format!("    {},\n", locale_variant(locale)));
    }
    out.push_str("}\n\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum TextKey {\n");
    for key in &keys {
        out.push_str(&format!("    {},\n", variant(key)));
    }
    out.push_str("}\n\npub fn text(locale: Locale, key: TextKey) -> &'static str {\n    match locale {\n");
    for (locale, _) in &locales {
        out.push_str(&format!(
            "        Locale::{} => {}(key),\n",
            locale_variant(locale),
            locale_fn(locale)
        ));
    }
    out.push_str("    }\n}\n\n");
    out.push_str(
        "pub fn text_with_args(locale: Locale, key: TextKey, vars: &[(&str, &str)]) -> String {\n",
    );
    out.push_str("    let mut rendered = text(locale, key).to_string();\n");
    out.push_str("    for (name, value) in vars {\n");
    out.push_str("        rendered = rendered.replace(&format!(\"{{{name}}}\"), value);\n");
    out.push_str("    }\n    rendered\n}\n\n");

    for (locale, pairs) in &locales {
        out.push_str(&format!("fn {}(key: TextKey) -> &'static str {{\n    match key {{\n", locale_fn(locale)));
        let mut ordered = pairs.clone();
        ordered.sort_by(|a, b| a.0.cmp(&b.0));
        for (key, value) in ordered {
            let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
            out.push_str(&format!("        TextKey::{} => \"{escaped}\",\n", variant(&key)));
        }
        out.push_str("    }\n}\n\n");
    }
    fs::write(out_file, out)
}

fn parse_flat(content: &str) -> Vec<(String, String)> {
    let mut pairs = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some((key, value)) = trimmed.split_once(':') else {
            continue;
        };
        let key = key.trim();
        if key.is_empty() {
            continue;
        }
        let value = value.trim().trim_matches('"').trim_matches('\'');
        pairs.push((key.to_string(), value.to_string()));
    }
    pairs
}

fn variant(key: &str) -> String {
    let mut name = String::new();
    let mut cap = true;
    for ch in key.chars() {
        if ch == '.' || ch == '_' || ch == '-' {
            cap = true;
            continue;
        }
        if cap {
            name.push(ch.to_ascii_uppercase());
            cap = false;
        } else {
            name.push(ch);
        }
    }
    name
}

fn locale_variant(locale: &str) -> &'static str {
    match locale {
        "en" => "EnUs",
        "zh" => "ZhCn",
        _ => panic!("unsupported locale {locale}"),
    }
}

fn locale_fn(locale: &str) -> &'static str {
    match locale {
        "en" => "en_us",
        "zh" => "zh_cn",
        _ => panic!("unsupported locale {locale}"),
    }
}
